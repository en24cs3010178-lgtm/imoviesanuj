/*
# Create movie booking records

1. New Tables
- `movie_bookings`
- `id` (uuid primary key generated by the database)
- `confirmation_code` (short customer-facing booking reference)
- `movie_title` (selected movie)
- `show_date` (selected calendar date)
- `show_time` (selected showtime)
- `cinema` (selected cinema location)
- `seats` (selected seat labels)
- `total_amount` (booking total in the app's currency)
- `customer_name` (name entered at checkout)
- `customer_email` (email entered at checkout)
- `status` (booking lifecycle status)
- `created_at` (creation timestamp)

2. Security
- Enable row-level security on `movie_bookings`.
- Allow the public booking flow to create records without sign-in.
- Do not expose booking history reads through the public client.
- Grant only INSERT access to the public and authenticated roles.

3. Important Notes
- This is intentionally a single-tenant booking table because the app does not include sign-in yet.
- Booking confirmation details are displayed immediately from the successful insert response in the browser.
*/

CREATE TABLE IF NOT EXISTS public.movie_bookings (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  confirmation_code text NOT NULL UNIQUE,
  movie_title text NOT NULL,
  show_date date NOT NULL,
  show_time text NOT NULL,
  cinema text NOT NULL,
  seats text[] NOT NULL,
  total_amount numeric(10,2) NOT NULL CHECK (total_amount >= 0),
  customer_name text NOT NULL,
  customer_email text NOT NULL,
  status text NOT NULL DEFAULT 'confirmed' CHECK (status IN ('confirmed', 'cancelled')),
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.movie_bookings ENABLE ROW LEVEL SECURITY;

GRANT INSERT ON public.movie_bookings TO anon, authenticated;

DROP POLICY IF EXISTS "Public can create movie bookings" ON public.movie_bookings;
CREATE POLICY "Public can create movie bookings"
ON public.movie_bookings
FOR INSERT
TO anon, authenticated
WITH CHECK (true);
